class ResearchDocument(Base):
    """
    One versioned document upload per research problem.

    evaluation_report JSONB schema:
      {
        format_issues:     [{section: str, issue: str}],
        plagiarism_matches: [{source: str, similarity: float, excerpt: str}],
        ai_highlights:     [{start: int, end: int, score: float}],
        clarity_notes:     str,
      }

    Human-gate: status APPROVED / REVISION_REQUESTED written only via guide
    review endpoint. Celery task writes only up to EVALUATED.
    """
    __tablename__ = "research_documents"
    __table_args__ = (
        Index("ix_research_documents_problem",  "research_problem_id"),
        Index("ix_research_documents_student",  "student_user_id"),
        Index("ix_research_documents_status",   "status"),
        Index("ix_research_documents_version",  "research_problem_id", "version"),
    )

    id                    = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    research_problem_id   = Column(
        UUID(as_uuid=True),
        ForeignKey("research_problems.id", ondelete="CASCADE"),
        nullable=False,
    )
    # Denormalized for fast queries without joining to research_problems
    student_user_id       = Column(UUID(as_uuid=True), nullable=False)

    version               = Column(Integer, nullable=False, default=1)

    # S3 object key
    file_url              = Column(String, nullable=True)
    file_name             = Column(String, nullable=True)

    # AI evaluation scores — written by Celery task only
    plagiarism_score      = Column(Float, nullable=True)    # max similarity 0–1
    ai_content_score      = Column(Float, nullable=True)    # 0–1
    format_score          = Column(Float, nullable=True)    # 0–1 (1 = fully compliant)
    clarity_score         = Column(Float, nullable=True)    # 0–1

    # Full structured evaluation report
    evaluation_report     = Column(JSONB, nullable=True)

    # AI provenance
    ai_model              = Column(String, nullable=True)
    prompt_hash           = Column(String, nullable=True)

    eval_job_id           = Column(UUID(as_uuid=True), nullable=True)

    status                = Column(
        Enum(DocumentStatus, native_enum=False),
        nullable=False,
        default=DocumentStatus.SUBMITTED,
    )

    # Guide review — written ONLY by guide review endpoint (human gate)
    guide_comment         = Column(Text, nullable=True)
    guide_reviewed_at     = Column(DateTime(timezone=True), nullable=True)

    submitted_at          = Column(
        DateTime(timezone=True), nullable=False, server_default=text("now()")
    )

    problem = relationship("ResearchProblem", back_populates="documents")
    viva_sessions = relationship(
        "VivaSession",
        back_populates="document",
        cascade="all, delete-orphan",
    )


