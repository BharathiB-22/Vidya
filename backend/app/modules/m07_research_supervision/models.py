class VivaSession(Base):
    """
    One async video viva session per student per document.

    Async viva design: student records video responses within a session window
    (expires_at). Questions are pre-generated from the document. Follow-up
    questions added after each base answer. Celery processes recording via
    Whisper ASR + LLM evaluation.

    ai_questions JSONB schema:
      [{id: str, text: str, source: "base"|"followup",
        based_on_qid: str|null, order: int}]

    ai_responses JSONB schema:
      [{question_id: str, response_text: str,
        start_ms: int|null, end_ms: int|null}]

    ai_evaluation JSONB schema (written by Celery only):
      [{question_id: str, coherence: float, accuracy: float,
        depth: float, comment: str}]

    guide_evaluation JSONB schema (written ONLY by guide ratify endpoint):
      [{question_id: str, score_override: float|null, comment: str|null}]

    Human-gate: status → GUIDE_RATIFIED and guide_evaluation only written via
    the guide ratify endpoint. overall_guide_score computed and stored there.
    """
    __tablename__ = "viva_sessions"
    __table_args__ = (
        UniqueConstraint("session_token", name="uq_viva_sessions_token"),
        Index("ix_viva_sessions_problem",    "research_problem_id"),
        Index("ix_viva_sessions_document",   "document_id"),
        Index("ix_viva_sessions_student",    "student_user_id"),
        Index("ix_viva_sessions_guide",      "guide_user_id"),
        Index("ix_viva_sessions_token",      "session_token"),
        Index("ix_viva_sessions_status",     "status"),
        Index("ix_viva_sessions_scheduled",  "scheduled_at"),
    )

    id                    = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    research_problem_id   = Column(
        UUID(as_uuid=True),
        ForeignKey("research_problems.id", ondelete="CASCADE"),
        nullable=False,
    )
    document_id           = Column(
        UUID(as_uuid=True),
        ForeignKey("research_documents.id", ondelete="CASCADE"),
        nullable=False,
    )
    student_user_id       = Column(UUID(as_uuid=True), nullable=False)
    guide_user_id         = Column(UUID(as_uuid=True), nullable=False)

    # Time-limited session access token
    session_token         = Column(String, nullable=False, unique=True)

    # AI-generated questions (written by schedule endpoint via viva_engine)
    ai_questions          = Column(JSONB, nullable=False, server_default="[]")

    # Student responses (written incrementally during session)
    ai_responses          = Column(JSONB, nullable=False, server_default="[]")

    # S3 path of combined recording upload
    video_url             = Column(String, nullable=True)
    transcript            = Column(Text, nullable=True)

    # AI evaluation — written ONLY by Celery process_viva_session task
    ai_evaluation         = Column(JSONB, nullable=True)
    overall_ai_score      = Column(Numeric(5, 2), nullable=True)

    # Guide evaluation — written ONLY by guide ratify endpoint (human gate)
    guide_evaluation      = Column(JSONB, nullable=True)
    overall_guide_score   = Column(Numeric(5, 2), nullable=True)

    # DPDP Act 2023 compliance — explicit student consent before recording
    consent_recorded      = Column(Boolean, nullable=False, default=False)

    # AI provenance
    ai_model              = Column(String, nullable=True)

    eval_job_id           = Column(UUID(as_uuid=True), nullable=True)

    scheduled_at          = Column(DateTime(timezone=True), nullable=True)
    expires_at            = Column(DateTime(timezone=True), nullable=True)
    completed_at          = Column(DateTime(timezone=True), nullable=True)
    ratified_at           = Column(DateTime(timezone=True), nullable=True)

    status                = Column(
        Enum(VivaStatus, native_enum=False),
        nullable=False,
        default=VivaStatus.SCHEDULED,
    )

    problem  = relationship("ResearchProblem", back_populates="viva_sessions")
    document = relationship("ResearchDocument", back_populates="viva_sessions")
