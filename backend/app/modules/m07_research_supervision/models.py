"""
M07 Research Supervision — SQLAlchemy models.

Tables (all tenant-schema, no schema= kwarg):
  research_problems   — student-proposed or guide-offered research problems
  research_documents  — versioned documents uploaded per research problem
  viva_sessions       — AI-conducted video viva session per document

Human-gate invariants:
  research_problems.status → ACCEPTED/REJECTED only via guide decision endpoint.
  research_documents.status → APPROVED/REVISION_REQUESTED only via guide review endpoint.
  viva_sessions.status → GUIDE_RATIFIED only via guide ratify endpoint.
  guide_evaluation is NEVER written by any Celery task.

Tenant isolation: all tables live in the tenant schema.
"""
from __future__ import annotations

import enum
import uuid

from sqlalchemy import (
    Boolean, Column, DateTime, Enum, Float,
    ForeignKey, Index, Integer, Numeric, String, Text,
    UniqueConstraint, text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import relationship

from app.database import Base


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class ProblemSource(str, enum.Enum):
    STUDENT_PROPOSED = "STUDENT_PROPOSED"
    AI_GENERATED     = "AI_GENERATED"


class ProblemStatus(str, enum.Enum):
    DRAFT              = "DRAFT"            # AI-generated, not yet offered to student
    PENDING_REVIEW     = "PENDING_REVIEW"   # student submitted; awaiting guide decision
    ACCEPTED           = "ACCEPTED"         # guide accepted
    REVISION_REQUESTED = "REVISION_REQUESTED"
    REJECTED           = "REJECTED"


class AIRecommendation(str, enum.Enum):
    ACCEPT = "ACCEPT"
    REVISE = "REVISE"
    REJECT = "REJECT"


class GuideDecision(str, enum.Enum):
    ACCEPT = "ACCEPT"
    REVISE = "REVISE"
    REJECT = "REJECT"


class DocumentStatus(str, enum.Enum):
    SUBMITTED          = "SUBMITTED"
    EVALUATING         = "EVALUATING"
    EVALUATED          = "EVALUATED"
    GUIDE_REVIEWED     = "GUIDE_REVIEWED"
    APPROVED           = "APPROVED"
    REVISION_REQUESTED = "REVISION_REQUESTED"


class VivaStatus(str, enum.Enum):
    SCHEDULED      = "SCHEDULED"
    IN_PROGRESS    = "IN_PROGRESS"
    COMPLETED      = "COMPLETED"      # recording uploaded, awaiting ASR
    ASR_PROCESSING = "ASR_PROCESSING" # Whisper + LLM evaluation running
    EVALUATED      = "EVALUATED"      # AI evaluation written; awaiting guide
    GUIDE_RATIFIED = "GUIDE_RATIFIED" # guide ratified — final


# ---------------------------------------------------------------------------
# ResearchProblem
# ---------------------------------------------------------------------------

class ResearchProblem(Base):
    """
    One research problem: either student-proposed or AI-generated by the guide.

    research_questions JSONB schema:
      [{question: str}]  — 1–5 research questions

    Human-gate: status transitions to ACCEPTED / REVISION_REQUESTED / REJECTED
    only via the guide decision endpoint. Celery tasks write only AI scores.
    """
    __tablename__ = "research_problems"
    __table_args__ = (
        Index("ix_research_problems_guide",   "guide_user_id"),
        Index("ix_research_problems_student", "student_user_id"),
        Index("ix_research_problems_status",  "status"),
        Index("ix_research_problems_source",  "source"),
        Index("ix_research_problems_created", "created_at"),
    )

    id                  = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)

    # Guide who owns / will supervise this problem
    guide_user_id       = Column(UUID(as_uuid=True), nullable=False)
    # Null for AI_GENERATED problems until a student is assigned
    student_user_id     = Column(UUID(as_uuid=True), nullable=True)

    title               = Column(String, nullable=False)
    abstract            = Column(Text, nullable=True)

    # [{question: str}]
    research_questions  = Column(JSONB, nullable=False, server_default="[]")

    source              = Column(
        Enum(ProblemSource, native_enum=False),
        nullable=False,
        default=ProblemSource.STUDENT_PROPOSED,
    )

    # AI evaluation outputs — written by Celery task only
    novelty_score       = Column(Numeric(4, 3), nullable=True)   # 0–1
    feasibility_score   = Column(Numeric(4, 3), nullable=True)   # 0–1
    clarity_score       = Column(Numeric(4, 3), nullable=True)   # 0–1
    ai_recommendation   = Column(
        Enum(AIRecommendation, native_enum=False),
        nullable=True,
    )
    ai_reasoning        = Column(Text, nullable=True)

    # AI provenance
    ai_model            = Column(String, nullable=True)
    prompt_hash         = Column(String, nullable=True)

    # FK to public.task_jobs for the evaluation Celery task
    eval_job_id         = Column(UUID(as_uuid=True), nullable=True)

    # Workflow status
    status              = Column(
        Enum(ProblemStatus, native_enum=False),
        nullable=False,
        default=ProblemStatus.PENDING_REVIEW,
    )

    # Guide decision — written ONLY by guide decision endpoint (human gate)
    guide_decision      = Column(
        Enum(GuideDecision, native_enum=False),
        nullable=True,
    )
    guide_note          = Column(Text, nullable=True)
    decided_at          = Column(DateTime(timezone=True), nullable=True)

    created_at          = Column(
        DateTime(timezone=True), nullable=False, server_default=text("now()")
    )
    updated_at          = Column(DateTime(timezone=True), nullable=True)

    documents = relationship(
        "ResearchDocument",
        back_populates="problem",
        cascade="all, delete-orphan",
        order_by="ResearchDocument.version",
    )
    viva_sessions = relationship(
        "VivaSession",
        back_populates="problem",
        cascade="all, delete-orphan",
    )


